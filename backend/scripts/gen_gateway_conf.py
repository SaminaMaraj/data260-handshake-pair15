"""Generate the nginx gateway config from services/common/routing.py.

The frontend keeps ONE API base URL (port 9150). The gateway forwards each
request to the service that owns its path, using the same longest-prefix
table the services use, so the two can never disagree.

Usage, from backend/:
    python scripts/gen_gateway_conf.py docker   > ../gateway/nginx.conf
    python scripts/gen_gateway_conf.py local    > ../gateway/nginx.local.conf

  docker: upstream hosts are p15-<service> (Compose / Kubernetes DNS names)
  local:  upstream hosts are 127.0.0.1 (services from scripts/run_services.sh)
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from services.common.routing import PORT_BASE, ROUTE_TABLE, SERVICE_PORTS


def render(mode: str) -> str:
    host = (lambda s: f"p15-{s}") if mode == "docker" else (lambda s: "127.0.0.1")
    lines = [
        "# GENERATED by backend/scripts/gen_gateway_conf.py - do not edit by hand.",
        "# Routes each API path to the owning p15 service (longest prefix wins).",
        "# Load-test finding (Nov 7): the nginx defaults (1 worker, 512 connections,",
        "# a new upstream connection per request) dropped requests above ~250 users",
        "# and returned 502s at 100-200 users. Hence the settings below.",
        "worker_processes auto;",
        "worker_rlimit_nofile 32768;",
        "events { worker_connections 8192; multi_accept on; }",
        "http {",
        "  include /etc/nginx/mime.types;" if mode == "docker" else "  # (no static files locally)",
        "  client_max_body_size 10m;  # PDF resume uploads",
        "  keepalive_requests 100000;  # clients may reuse one connection",
        "  access_log off;             # each service logs its own requests (JSON)",
    ]
    # One pool of reusable connections per service instead of a new TCP
    # connection (and an exhausted local port) for every request.
    for service in sorted(set(ROUTE_TABLE.values())):
        lines += [f"  upstream p15_{service} {{",
                  f"    server {host(service)}:{SERVICE_PORTS[service]};",
                  "    keepalive 64;",
                  "  }"]
    lines += [
        f"  server {{",
        f"    listen {PORT_BASE};",
        "    location = /health { default_type application/json; return 200 "
        "'{\"status\":\"ok\",\"service\":\"p15-gateway\","
        "\"message\":\"Handshake Pair 15 API is running\"}'; }",
    ]
    if mode == "docker":
        # The React build is baked into this image (frontend/Dockerfile), so the
        # app and the API share one origin: no CORS, one LoadBalancer on EKS.
        lines += [
            "    root /usr/share/nginx/html;",
            "    location = / { try_files /index.html =404; add_header Cache-Control no-store; }",
            "    location ^~ /assets/ { expires 7d; }",
            "    location = /favicon.svg { }",
            "    location = /icons.svg { }",
        ]
    # nginx already prefers the longest matching prefix; "^~" stops regex
    # checks, and the "/prefix/" + "= /prefix" pair keeps /jobsearch from
    # matching /jobs.
    for prefix in sorted(ROUTE_TABLE, key=len, reverse=True):
        service = ROUTE_TABLE[prefix]
        for loc in (f"= {prefix}", f"^~ {prefix}/"):
            lines += [
                f"    location {loc} {{",
                f"      proxy_pass http://p15_{service};",
                "      proxy_http_version 1.1;           # needed for upstream keepalive",
                "      proxy_set_header Connection \"\";",
                "      proxy_set_header Host $host;",
                "      proxy_set_header X-Request-ID $request_id;",
                "      proxy_read_timeout 180s;  # assistant calls wait on the model",
                "    }",
            ]
    lines += [
        "    location / { default_type application/json; "
        "return 404 '{\"detail\":\"Not Found\"}'; }",
        "  }", "}", "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    mode = sys.argv[1] if len(sys.argv) > 1 else "docker"
    if mode not in ("docker", "local"):
        sys.exit("mode must be 'docker' or 'local'")
    sys.stdout.write(render(mode))
